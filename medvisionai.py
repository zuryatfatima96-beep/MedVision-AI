class ResNet18UNet(nn.Module):

    def __init__(self, num_classes=NUM_CLASSES):

        super().__init__()

        backbone = models.resnet18(
            weights=None
        )

        self.enc1 = nn.Sequential(
            backbone.conv1,
            backbone.bn1,
            backbone.relu
        )

        self.pool1 = backbone.maxpool

        self.enc2 = backbone.layer1
        self.enc3 = backbone.layer2
        self.enc4 = backbone.layer3
        self.enc5 = backbone.layer4

        self.up4 = nn.ConvTranspose2d(
            512, 256, 2, stride=2
        )

        self.dec4 = self.conv_block(
            512, 256
        )

        self.up3 = nn.ConvTranspose2d(
            256, 128, 2, stride=2
        )

        self.dec3 = self.conv_block(
            256, 128
        )

        self.up2 = nn.ConvTranspose2d(
            128, 64, 2, stride=2
        )

        self.dec2 = self.conv_block(
            128, 64
        )

        self.up1 = nn.ConvTranspose2d(
            64, 64, 2, stride=2
        )

        self.dec1 = self.conv_block(
            128, 64
        )

        self.up0 = nn.ConvTranspose2d(
            64, 32, 2, stride=2
        )

        self.final = nn.Sequential(
            nn.Conv2d(
                32, 32, 3, padding=1
            ),
            nn.BatchNorm2d(32),
            nn.ReLU(inplace=True),

            nn.Conv2d(
                32,
                num_classes,
                1
            )
        )


    @staticmethod
    def conv_block(
        in_channels,
        out_channels
    ):

        return nn.Sequential(

            nn.Conv2d(
                in_channels,
                out_channels,
                3,
                padding=1
            ),

            nn.BatchNorm2d(
                out_channels
            ),

            nn.ReLU(
                inplace=True
            ),

            nn.Conv2d(
                out_channels,
                out_channels,
                3,
                padding=1
            ),

            nn.BatchNorm2d(
                out_channels
            ),

            nn.ReLU(
                inplace=True
            )
        )


    def forward(self, x):

        e1 = self.enc1(x)
        p1 = self.pool1(e1)

        e2 = self.enc2(p1)
        e3 = self.enc3(e2)
        e4 = self.enc4(e3)
        e5 = self.enc5(e4)

        d4 = self.up4(e5)
        d4 = torch.cat(
            [d4, e4],
            dim=1
        )
        d4 = self.dec4(d4)

        d3 = self.up3(d4)
        d3 = torch.cat(
            [d3, e3],
            dim=1
        )
        d3 = self.dec3(d3)

        d2 = self.up2(d3)
        d2 = torch.cat(
            [d2, e2],
            dim=1
        )
        d2 = self.dec2(d2)

        d1 = self.up1(d2)
        d1 = torch.cat(
            [d1, e1],
            dim=1
        )
        d1 = self.dec1(d1)

        out = self.up0(d1)

        out = self.final(out)

        return out


